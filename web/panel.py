"""Quality panel for the web data (docs/PANEL.md): automatic diagnostics over every generated
disease, instead of eyeballing a single one.

    py -3 -m web.build --sample 60     # random sample (seed 0)
    py -3 -m web.panel
"""
import glob
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web" / "public" / "data"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ds = []
    for f in glob.glob(str(WEB / "d" / "*.json")):
        ds += list(json.loads(Path(f).read_text("utf-8")).values())
    n = len(ds)
    cand = [c for d in ds for c in d["candidates"]]
    top10 = Counter(c["name"] for d in ds for c in d["candidates"][:10])
    top10_nu = Counter(c["name"] for d in ds for c in d["no_use"][:5])
    risks = np.mean([c["risk"] for c in cand])
    no_expl = np.mean([not c["expl"] for c in cand])
    expl_types = Counter(e["t"] for c in cand for e in c["expl"])
    # Which disease the «shared genes» line comes from: if one dominates, it is a hub (P28)
    source_s = Counter(next(m[0] for m in e["m"] if m[1] >= 3 and (len(m) < 4 or m[3] < 1e-6))
                       for c in cand for e in c["expl"] if e["t"] == "similar" and "shared_genes" in c.get("lines", []))
    empty = np.mean([not d["candidates"] and not d["extensions"] for d in ds])
    with_atc = np.mean([bool(c.get("atc")) for c in cand])
    with_mech = np.mean([bool(c.get("mechanism")) for c in cand])
    empty_nu = np.mean([not d["no_use"] for d in ds])
    no_targets = np.mean([not d["targets"] for d in ds])
    L = ["# Explorer quality panel\n",
         f"Generated by `web/panel.py` over {n} generated diseases (all of them, or the sample of 60 + the 24 test ones).\n",
         "> Quality-control output for developers: the per-disease candidate lists are **research hypotheses, "
         "not treatment recommendations**, and contain errors. Use the website for the evidence behind each one.\n",
         "## Automatic diagnostics\n",
         f"- Candidates per disease: {np.mean([len(d['candidates']) for d in ds]):.1f} on average.",
         f"- Candidates **with no explanation at all**: {no_expl:.1%}.",
         f"- Direct extensions per disease: {np.mean([len(d['extensions']) for d in ds]):.1f}; diseases with no "
         f"candidate and no extension: {empty:.0%}.",
         f"- Candidates with an ATC class: {with_atc:.0%}; with known targets: {with_mech:.0%}; grouped with salts or esters: "
         f"{sum(len(c.get('also', [])) for c in cand)}.",
         "- Diseases that most often give the «shared genes» line: "
         + ", ".join(f"{k} ({v})" for k, v in source_s.most_common(8)) + ".",
         f"- Candidates with a possible-risk warning: {risks:.1%}.",
         f"- Diseases with little information (< 5 candidates): {np.mean([d['little_info'] for d in ds]):.0%}; "
         f"candidates hidden for lack of evidence: {np.mean([d['hidden'] for d in ds]):.1f} per disease.",
         f"- Diseases with an empty «no prior use» list: {empty_nu:.0%}; with no targets: {no_targets:.0%}.",
         "- Explanation types: " + ", ".join(f"{k} {v}" for k, v in expl_types.most_common()) + ".",
         "",
         "## Drugs repeated most often among the top 10 candidates",
         "If a drug shows up for many different diseases, it is a generic (unspecific) candidate.\n",
         "| Drug | Diseases (of {}) |".format(n), "|---|---|"]
    L += [f"| {k} | {v} ({v / n:.0%}) |" for k, v in top10.most_common(15)]
    L += ["", "## Drugs with no prior use repeated most often (top 5)\n", "| Drug | Diseases |", "|---|---|"]
    L += [f"| {k} | {v} ({v / n:.0%}) |" for k, v in top10_nu.most_common(10)]
    L += ["", "## Sample to review by hand (top 5 candidates)\n"]
    for d in sorted(ds, key=lambda d: d["name"].lower()):
        c5 = "; ".join(c["name"] + (" [⚠]" if c["risk"] else "") for c in d["candidates"][:5])
        tn = ", ".join(x["gene"] for x in (d["targets"] or {}).get("new", [])[:3])
        L.append(f"- **{d['name']}** ({d['n_genes']} genes, {len(d['approved'])} approved): {c5}"
                 + (f" · targets: {tn}" if tn else ""))
    (ROOT / "docs" / "PANEL.md").write_text("\n".join(L) + "\n", "utf-8")
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main()
