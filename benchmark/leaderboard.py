"""Builds LEADERBOARD.md from predictions/<model>/results.json (run «bench.py evaluate» first)."""
import json
from pathlib import Path

import pandas as pd

from bench import summary

HERE = Path(__file__).resolve().parent
NAMES = {"popularity": "Popularity (baseline, ignores the disease)",
         "txgnn": "TxGNN (Huang et al., Nat Med 2024; official code, trained on the same splits)",
         "orevid_no_popularity": "OREVID, graph only (logistic regression, no popularity)",
         "orevid_lambdarank": "OREVID (LambdaRank over meta-paths)"}
ORDER = ["popularity", "txgnn", "orevid_no_popularity", "orevid_lambdarank"]


def fmt(x):
    return "–" if pd.isna(x) else f"{x:.3f}"


def main():
    res = {}
    for m in ORDER:
        f = HERE / "predictions" / m / "results.json"
        if f.exists():
            res[m] = summary(json.loads(f.read_text()))
    L = ["# Leaderboard\n",
         "Generated by `leaderboard.py`. Every model is evaluated with `bench.py evaluate` on exactly the "
         "same tasks. Recall@100: fraction of a disease's drugs found in the top 100 of the 7,957 candidates "
         "(mean over diseases). Precision@K: hits in the top K, K = number of the disease's drugs. "
         "AUPRC: TxGNN's protocol (positives vs as many random approved drugs).\n"]
    blocks = [("Zero-shot (5 seeds)", "zero-shot (5 seeds)", ["all", "hard"]),
              ("Disease areas (9, one seed)", "disease areas (9)", ["all", "hard"]),
              ("Novelty (zero-shot)", "zero-shot (5 seeds)", ["A_approved_only", "B_no_blockbusters", "C_no_prior_use"]),
              ("External: Open Targets 26.06 approvals not in PrimeKG", "external (Open Targets 26.06)",
               ["all", "recent", "non_obvious"])]
    for title, group, subs in blocks:
        L.append(f"## {title}\n")
        hdr = "| Model | " + " | ".join(f"{s} R@100 | {s} P@K" for s in subs) + (" | AUPRC |" if group != "external (Open Targets 26.06)" and "A_approved_only" not in subs else " |")
        L.append(hdr)
        L.append("|---|" + "---|---|" * len(subs) + ("---|" if hdr.endswith("AUPRC |") else ""))
        for m in ORDER:
            if m not in res:
                continue
            d = res[m]
            d = d[d.group == group]
            cells = []
            for s in subs:
                r = d[d.subset == s]
                cells += [fmt(r["Recall@100"].iloc[0]) if len(r) else "–", fmt(r["Precision@K"].iloc[0]) if len(r) else "–"]
            if hdr.endswith("AUPRC |"):
                r = d[d.subset == "all"]
                cells.append(fmt(r["AUPRC"].iloc[0]) if len(r) and "AUPRC" in r else "–")
            L.append(f"| {NAMES[m]} | " + " | ".join(cells) + " |")
        L.append("")
    (HERE / "LEADERBOARD.md").write_text("\n".join(L), "utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
