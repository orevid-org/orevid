"""Fairer comparison with TxGNN: measures the two protocol differences instead of only stating them.

1. Training labels. OREVID normally uses each split's validation edges as extra training labels;
   TxGNN uses them only for early stopping. `orevid_lambdarank_train_only` is OREVID trained with the
   training edges only (`python -m evaluation.txgnn ... --train-only`).
2. Degenerate TxGNN scores. For test diseases with no edge left in the training graph TxGNN outputs the
   same score for every drug, so its ranking there is random. Those diseases are excluded below.

    python fair_comparison.py          # -> FAIR_COMPARISON.md (needs the prediction files, see README)
"""
import json
from pathlib import Path

import numpy as np

from bench import load_predictions, txgnn_metrics

HERE = Path(__file__).resolve().parent
MODELS = {"popularity": "Popularity (baseline)", "txgnn": "TxGNN (official code, same splits)",
          "orevid_lambdarank": "OREVID (standard: training + validation labels)",
          "orevid_lambdarank_train_only": "OREVID (training labels only, like TxGNN)"}
METRICS = ["Recall@100", "Precision@K", "AUPRC"]


def degenerate(S):
    """Columns (diseases) where every drug gets the same score."""
    return np.flatnonzero(np.nanstd(S, axis=0) == 0)


def per_task(task):
    drugs = np.asarray(task["drugs"])
    where = {v: i for i, v in enumerate(drugs)}
    positives = [np.array([where[p] for p in r["positives"]]) for r in task["diseases"]]
    pool = np.asarray(task["train_popularity"]) > 0
    hard = {i for i, r in enumerate(task["diseases"]) if r["near_duplicate_overlap"] < 0.5}
    S = {}
    for m in MODELS:
        f = HERE / "predictions" / m / f"{task['name']}.parquet"
        if f.exists():
            S[m] = load_predictions(f, task)[0]
    if "txgnn" not in S:
        return None
    bad = set(degenerate(S["txgnn"]).tolist())
    subsets = {"all": list(range(len(positives))),
               "all, without degenerate TxGNN": [i for i in range(len(positives)) if i not in bad],
               "hard": sorted(hard),
               "hard, without degenerate TxGNN": sorted(hard - bad)}
    out = {"n_degenerate": len(bad), "n_diseases": len(positives)}
    for sub, cols in subsets.items():
        if not cols:
            continue
        out[sub] = {m: txgnn_metrics(s[:, cols], [positives[i] for i in cols], pool) for m, s in S.items()}
    return out


def main():
    res = {}
    for tf in sorted((HERE / "tasks").glob("*.json")):
        task = json.loads(tf.read_text())
        if task.get("type") == "external":
            continue
        r = per_task(task)
        if r:
            res[task["name"]] = r
            print(f"  {task['name']}: {r['n_degenerate']} of {r['n_diseases']} diseases with degenerate TxGNN scores")
    L = ["# Fairer comparison with TxGNN\n",
         "Generated by `fair_comparison.py`. It measures the two protocol differences listed in the benchmark "
         "README instead of only stating them: (1) OREVID retrained with the training labels only, as TxGNN "
         "(which uses the validation labels only for early stopping); (2) the test diseases where TxGNN outputs "
         "the same score for every drug (no edge left in its training graph) are excluded. Means over the 5 "
         "zero-shot seeds and over the 9 disease areas.\n"]
    for group, prefix in [("Zero-shot (5 seeds)", "zero_shot"), ("Disease areas (9, one seed)", "area_")]:
        keys = [k for k in res if k.startswith(prefix)]
        if not keys:
            continue
        nd = sum(res[k]["n_degenerate"] for k in keys)
        nt = sum(res[k]["n_diseases"] for k in keys)
        L.append(f"## {group}\n\nDiseases with degenerate TxGNN scores: {nd} of {nt} (summed over tasks).\n")
        for sub in ["all", "all, without degenerate TxGNN", "hard", "hard, without degenerate TxGNN"]:
            rows = [k for k in keys if sub in res[k]]
            if not rows:
                continue
            L.append(f"**{sub}**\n\n| Model | " + " | ".join(METRICS) + " |\n|---|" + "---|" * len(METRICS))
            for m, name in MODELS.items():
                v = [res[k][sub][m] for k in rows if m in res[k][sub]]
                if len(v) == len(rows):
                    L.append(f"| {name} | " + " | ".join(f"{np.mean([x[met] for x in v]):.3f}" for met in METRICS) + " |")
            L.append("")
    (HERE / "FAIR_COMPARISON.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (HERE / "fair_comparison.json").write_text(json.dumps(res, indent=1))
    print("-> FAIR_COMPARISON.md")


if __name__ == "__main__":
    main()
