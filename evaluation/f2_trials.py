"""F2 (docs/IMPROVEMENT_PLAN.md, «Registered 09-11-2026 (home PC, night): F2»): trials found through their registered
ClinicalTrials.gov conditions (web/framing.py, `trials_registered_here`). Display only.

    py -3 -m sources.ctgov conditions        # conditions and condition MeSH ids for every Open Targets trial record
    py -3 -m evaluation.f2_trials sample     # -> data/eval/f2_frames.pkl, docs/F2_TRIAL_CONDITIONS.md (check by hand)
    py -3 -m evaluation.f2_trials apply      # writes the field into web/public/data/d/*.json (only after the check)
"""
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "web" / "public" / "data" / "d"
PKL = ROOT / "data" / "eval" / "f2_frames.pkl"
FIELD = "trials_registered_here"
MPNST = 36459


def sample(variant="b"):
    """variant "a" = F2 (both routes, seed 1; not passed); "b" = F2b (name route only, seed 2, F2's sample excluded)."""
    sys.stdout.reconfigure(encoding="utf-8")
    routes = ("MeSH", "name") if variant == "a" else ("name",)
    from graph import Graph
    from evaluation.twins import twins
    from web.framing import Framing
    g = Graph()
    F = Framing(g)
    tw = twins(g, "disease")
    pages = {}
    for fj in sorted(DEST.glob("*.json")):
        pages.update({int(k): v["name"] for k, v in json.loads(fj.read_text("utf-8")).items()})
    frames = {}
    for k, d in enumerate(sorted(pages)):
        frames[d] = F.trials_registered_here(tw.get(d, {d}), routes)
        if (k + 1) % 2000 == 0:
            print(f"  {k + 1}/{len(pages)}", flush=True)
    pd.to_pickle(frames, PKL)
    entries = [(pages[d], drug, r[0], r[1], r[2], r[3]) for d, f in frames.items() for drug, recs in f.items()
               for r in recs if r[0] != "+"]
    rng = np.random.default_rng(1 if variant == "a" else 2)
    if variant == "b":
        f2_ncts = {"NCT01028534", "NCT03919292", "NCT00347204", "NCT03633955", "NCT00089726", "NCT00028730", "NCT00888342",
                   "NCT02730312", "NCT02218164", "NCT00000620", "NCT00352313", "NCT00126646", "NCT03199313", "NCT01590732",
                   "NCT00140998", "NCT00004734", "NCT00725634", "NCT01702636", "NCT03938389", "NCT06129643"}
        entries = [e for e in entries if e[2] not in f2_ncts]
    pick = [entries[i] for i in rng.choice(len(entries), min(20, len(entries)), replace=False)] if entries else []
    routes = Counter(e[5] for e in entries)
    reg = F._registered
    n_mesh = sum(bool(v[1]) for v in reg.values())
    mp = frames.get(MPNST, {})
    L = ["# F2. Trials found through their registered conditions (display only)\n",
         "Generated by `py -3 -m evaluation.f2_trials sample`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 09-11-2026 "
         "(home PC, night), before any run: F2».\n", "## Coverage\n",
         f"- Open Targets clinical-trial records with their registered conditions: {len(reg):,} (with condition MeSH ids: {n_mesh:,}).",
         f"- Added (page, drug, trial) entries: {len(entries):,} on {sum(bool(f) for f in frames.values()):,} pages; by route: "
         + ", ".join(f"{k} {v:,}" for k, v in routes.items()) + " (shown: at most 3 trials per drug).",
         f"- MPNST page (36459), added: " + ("; ".join(f"{drug}: " + ", ".join(r[0] for r in recs if r[0] != "+")
                                                       for drug, recs in mp.items()) or "none") + ".",
         f"- Sorafenib on the MPNST page: {'; '.join(r[0] + ' (' + r[1] + ')' for r in mp.get('Sorafenib', [])) or 'not added'}.\n",
         "## Check: 20 random added entries (criterion: the page's disease is one of the registered conditions, or a direct "
         "synonym of one, in at least 19 of 20)\n",
         "| Page | Drug | Trial | Phase | Registered conditions | Route | Right? |", "|---|---|---|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d} | {e} | {f} | (to fill) |" for a, b, c, d, e, f in pick]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / ("F2_TRIAL_CONDITIONS.md" if variant == "a" else "F2B_TRIAL_CONDITIONS.md")).write_text(text, "utf-8")
    print(text)


def apply():
    sys.stdout.reconfigure(encoding="utf-8")
    frames = pd.read_pickle(PKL)
    n = 0
    for fj in sorted(DEST.glob("*.json")):
        pages = json.loads(fj.read_text("utf-8"))
        for k, v in pages.items():
            f = frames.get(int(k))
            if f:
                v[FIELD] = f
                n += 1
            else:
                v.pop(FIELD, None)
        fj.write_text(json.dumps(pages, ensure_ascii=False, separators=(",", ":"), allow_nan=False), "utf-8")
    print(f"pages with added trials: {n:,}")


if __name__ == "__main__":
    apply() if sys.argv[1:] == ["apply"] else sample("a" if "a" in sys.argv[1:] else "b")
