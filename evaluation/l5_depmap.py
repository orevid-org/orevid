"""L5 gate: do the targets of drugs approved for a cancer lineage matter more to that lineage (DepMap CRISPR) than to
the others? (docs/IMPROVEMENT_PLAN.md, «Registered 24-10-2026: L1–L6»; lineages: resources/depmap_lineages.csv and
resources/prism_lineages.csv, written before reading any effect).

Per lineage: genes that are targets of any approved drug; positives = targets of drugs approved (PrimeKG or confirmed
Open Targets) for a cancer of the lineage. Score = −(median effect in the lineage − the gene's median over lineages).
AUROC per lineage, mean over lineages with a 95 % interval resampling lineages; passes if above 0.5.

    py -3 -m evaluation.l5_depmap      # -> data/eval/l5_depmap.json, docs/L5_DEPMAP.md
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from evaluation.o2_prism import boot, lineage_diseases

ROOT = Path(__file__).resolve().parent.parent


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from graph import INDICATION, Graph
    from predictor import drug_status
    g = Graph()
    status = drug_status(g)
    I = g.M(INDICATION).tocsr()
    T = g.M("drug_protein|moa").tocsr()
    ot = pd.read_parquet(ROOT / "data" / "ext" / "ot_approvals.parquet")
    ot = ot[ot.status == "confirmed"]
    appr = defaultdict(set)  # drug -> diseases
    for f in g.drugs:
        if status.get(int(f)) == "approved":
            appr[int(f)] |= set(I.indices[I.indptr[f]:I.indptr[f + 1]].tolist())
    for f, d in zip(ot.x_index.astype(int), ot.y_index.astype(int)):
        if status.get(f) == "approved":
            appr[f].add(d)
    targets = {f: set(T.indices[T.indptr[f]:T.indptr[f + 1]].tolist()) for f in appr}
    all_targets = set().union(*targets.values())
    eff = pd.read_parquet(ROOT / "data" / "ext" / "depmap_lineage.parquet")
    wide = eff.pivot(index="gene", columns="lineage", values="effect")
    rel = wide.sub(wide.median(axis=1), axis=0)
    dm = pd.read_csv(ROOT / "resources" / "depmap_lineages.csv", comment="#")
    lin_d = lineage_diseases(g)
    rows = []
    for (dep, lin), _ in dm.groupby(["depmap", "lineage"]):
        if dep not in rel.columns:
            continue
        D = lin_d.get(lin, set())
        pos_genes = set().union(*(targets[f] for f, ds in appr.items() if ds & D)) if D else set()
        genes = [x for x in rel.index if x in all_targets]
        y = np.array([x in pos_genes for x in genes])
        if not y.any() or y.all():
            continue
        s = -rel.loc[genes, dep].to_numpy()
        ok = ~np.isnan(s)
        rows.append({"depmap": dep, "lineage": lin, "genes": int(ok.sum()), "positives": int(y[ok].sum()),
                     "auroc": float(roc_auc_score(y[ok], s[ok]))})
    rng = np.random.default_rng(0)
    r = pd.DataFrame(rows)
    res = {"lineages": rows, "auroc": boot(r.auroc, rng)}
    res["passes"] = bool(res["auroc"][1] > 0.5)
    (ROOT / "data" / "eval" / "l5_depmap.json").write_text(json.dumps(res, indent=1), "utf-8")
    L = ["# L5. DepMap CRISPR dependency of approved oncology targets by lineage\n",
         "Generated by `py -3 -m evaluation.l5_depmap`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 24-10-2026: L1–L6». "
         "DepMap Public 24Q2 (CC BY 4.0) median Chronos effect per gene and lineage; genes = targets of approved drugs; "
         "positives = targets of drugs approved for a cancer of the lineage; score = lineage-specific dependency.\n",
         f"**Mean AUROC {res['auroc'][0]:.3f} ({res['auroc'][1]:.3f}–{res['auroc'][2]:.3f})** over {len(rows)} lineage pairs.\n",
         "| DepMap lineage | PRISM lineage | Target genes | Positives | AUROC |", "|---|---|---|---|---|"]
    L += [f"| {x['depmap']} | {x['lineage']} | {x['genes']} | {x['positives']} | {x['auroc']:.3f} |" for x in rows]
    L += ["", f"**Gate:** {'passes → a feature test is to be registered' if res['passes'] else 'does not pass'}.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "L5_DEPMAP.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
