"""Validation of the biomarker rule for disease subtypes (resources/biomarker_subtypes.csv; web/build.py
`marker_rules`; docs/REVIEW_RESPONSE.md T7). Criteria fixed before running:

    (a) list every (drug, disease) pair the rule removes from a page, for a manual check;
    (b) no flagged pair may be an approved indication (DrugBank or a confirmed Open Targets approval)
        of that subtype; flagged pairs with a phase 3 trial in the subtype are listed for the check;
    (c) count the candidates and direct extensions it removes.

    py -3 -m evaluation.biomarker_check     # -> docs/BIOMARKERS.md
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from graph import CLINICAL, INDICATION
    from evaluation.twins import twin_neighbors
    from web.build import DiseasePages
    P = DiseasePages()
    g, gc = P.g, P.gc
    rules = {d: r for d, r in P.markers.items() if any(st == "absent" for _, st, _ in r)}
    L = ["# Biomarker-defined subtypes: validation of the exclusion rule\n",
         "Generated by `evaluation/biomarker_check.py`. Rule and table: `web/build.py` `marker_rules`, "
         "`resources/biomarker_subtypes.csv` (an absent marker also applies to the more specific forms). "
         "Criteria fixed before running (docs/REVIEW_RESPONSE.md, T7).\n"]
    approved_conflicts, trial_pairs, removed_rows = [], [], []
    n_cand = n_ext = 0
    for d in sorted(rules):
        dt = P.twins.get(d, {d})
        flagged = {}
        for marker, st, ds in rules[d]:
            if st == "absent":
                for f in ds:
                    flagged.setdefault(f, marker)
        indicated = twin_neighbors(gc, dt, INDICATION) | {i for i in twin_neighbors(gc, dt, "clinical:approved")
                                                          if any((i, m) in P.ot_confirmed for m in dt)}
        for f in sorted(set(flagged) & indicated):
            approved_conflicts.append((g.name(d), g.name(f), flagged[f]))
        for f in sorted(set(flagged) & twin_neighbors(gc, dt, f"{CLINICAL}:phase 3")):
            trial_pairs.append((g.name(d), g.name(f), flagged[f]))
        if not P.has_page[d]:
            continue
        with_rule = P.disease(d)
        saved, P.markers = P.markers, {}
        without = P.disease(d)
        P.markers = saved
        names = lambda page, k: {c["name"] for c in page[k]} | {a for c in page[k] for a in c.get("also", [])}
        lost_c = names(without, "candidates") - names(with_rule, "candidates")
        lost_e = names(without, "extensions") - names(with_rule, "extensions")
        n_cand += len(lost_c)
        n_ext += len(lost_e)
        for n, m in with_rule["excluded_marker"]:
            removed_rows.append((g.name(d), n, m, "candidate" if n in lost_c else ("extension" if n in lost_e else "hidden")))
    L += [f"Diseases with an absent marker (with descendants): {len(rules)}; with a website page: "
          f"{sum(bool(P.has_page[d]) for d in rules)}.\n",
          f"**(b) Approved indications among the flagged pairs: {len(approved_conflicts)}** "
          f"(must be 0).\n"]
    L += [f"- {a} — {b} ({m})" for a, b, m in approved_conflicts]
    L += ["", f"Flagged pairs with a phase 3 trial in the subtype (manual check): {len(trial_pairs)}\n"]
    L += [f"- {a} — {b} ({m})" for a, b, m in trial_pairs]
    L += ["", f"**(c) Removed from the pages: {n_cand} candidates and {n_ext} direct extensions** "
          f"(the rest of the removed drugs would have been hidden for lack of evidence).\n",
          "**(a) Every removed pair** (drug that the model ranked in the top 25 window of the page):\n",
          "| Disease | Drug | Marker absent | Would have been |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {m} | {w} |" for a, b, m, w in removed_rows]
    out = ROOT / "docs" / "BIOMARKERS.md"
    out.write_text("\n".join(L) + "\n", "utf-8")
    print("\n".join(L[:12]))
    print(f"... {len(removed_rows)} removed pairs -> {out}")


if __name__ == "__main__":
    main()
