"""R3: anti-infectives of the wrong pathogen class, with MONDO classes and ATC codes (roadmap item 8).

Protocol and decision rule: docs/IMPROVEMENT_PLAN.md, «Registered 23-10-2026, before any run: R3» (pushed before
the downloads). Same top 25, sections and sets as evaluation/evidence_ci.py; same rule as R2 (evaluation/r1_r2.py).

    py -3 -m evaluation.r3_infections        # -> data/eval/r3_infections.json, docs/R3_INFECTIONS.md
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

from evaluation.evidence_ci import Genes, bench_task, bootstrap, external_task, fmt
from evaluation.r1_r2 import removed_from_shown

ROOT = Path(__file__).resolve().parent.parent


def r3_drop(t, dis_cls, drug_cls, ind):
    """drugs × D: candidates hidden by R3; `ind` = indication matrix of the graph the model sees."""
    from sources.infections import WRONG
    drugs = t["g"].drugs
    drop = np.zeros((len(drugs), len(t["D"])), bool)
    for c, d in enumerate(t["D"]):
        dc = dis_cls.get(int(d), set())
        if len(dc) != 1:
            continue
        (cls,) = dc
        for j, f in enumerate(drugs):
            k = drug_cls.get(int(f))
            if not k or cls in k or not k <= WRONG[cls]:
                continue
            treated = ind.indices[ind.indptr[f]:ind.indptr[f + 1]]
            if any(cls in dis_cls.get(int(m), ()) for m in treated):
                continue  # exemption: indicated for a disease of the same class
            drop[j, c] = True
    return drop


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    import pandas as pd
    from evaluation.txgnn import AREAS, INDICATION, load_kg, node_types
    from graph import Graph
    from sources.infections import disease_class_fn, drug_classes
    t0 = time.time()
    kg = load_kg()
    types = node_types(kg)
    gc = Graph()
    fn = disease_class_fn()
    n = gc.nodes
    dis_cls = {int(i): fn(nid, name) for i, t, nid, name in zip(n.node_index, n.node_type, n.node_id, n.node_name)
               if t == "disease"}
    drug_cls = drug_classes(gc)
    ot = pd.read_parquet(ROOT / "data" / "ext" / "ot_approvals.parquet")
    ot_conf = set(zip(ot[ot.status == "confirmed"].x_index.astype(int), ot[ot.status == "confirmed"].y_index.astype(int)))
    full_ind = gc.M(INDICATION).tocsr()
    rng = np.random.default_rng(0)
    store, pairs, infect = {}, [], {}
    groups = {"benchmark": [("complex_disease", s) for s in (1, 2, 3, 4, 5)], "areas": [(a, 1) for a in AREAS]}
    tasks = [(grp, split, seed) for grp, lst in groups.items() for split, seed in lst] + [("external", None, None)]
    for grp, split, seed in tasks:
        t = external_task(kg, types) if grp == "external" else bench_task(kg, types, split, seed)
        hits = t["hits"]
        T = Genes(t["g"], t["D"]).table("base")
        drop = r3_drop(t, dis_cls, drug_cls, t["g"].M(INDICATION).tocsr())
        rem, prs = removed_from_shown(t["top"], t["V"], T, drop, hits)
        store.setdefault((grp, "removed"), []).append(tuple(rem.T))
        for c, d in enumerate(t["D"]):
            k = dis_cls.get(int(d), set())
            if len(k) == 1:
                infect.setdefault(grp, {}).setdefault(next(iter(k)), 0)
                infect[grp][next(iter(k))] += 1
        for c, j in prs:
            f, d = int(t["g"].drugs[j]), int(t["D"][c])
            pairs.append({"set": grp, "split": split, "disease": gc.name(d), "drug": gc.name(f), "hit": bool(hits[c][j]),
                          "class": sorted(dis_cls[d])[0], "drug_classes": sorted(drug_cls.get(f, ())),
                          "approved": bool(d in set(full_ind.indices[full_ind.indptr[f]:full_ind.indptr[f + 1]].tolist())
                                           or (f, d) in ot_conf)})
        print(f"  {grp} {split} {seed}: removed {int(rem[:, 1].sum())} ({time.time() - t0:.0f} s)", flush=True)
    res = {"|".join(k): bootstrap(v, rng) for k, v in store.items()}
    rep = json.loads((ROOT / "data" / "ext" / "infections.json").read_text("utf-8"))
    out = {"results": res, "infectious_test_diseases": infect, "pairs": pairs, "sources": rep}
    (ROOT / "data" / "eval" / "r3_infections.json").write_text(json.dumps(out, indent=1), "utf-8")
    report(out)


def report(out=None):
    out = out or json.loads((ROOT / "data" / "eval" / "r3_infections.json").read_text("utf-8"))
    R, S = out["results"], out["sources"]
    inf = lambda grp: (R.get(f"{grp}|removed") or (0, 0, 0, 0))
    L = ["# R3. Anti-infectives of the wrong pathogen class (MONDO classes, ATC codes)\n",
         "Generated by `py -3 -m evaluation.r3_infections`. Rule fixed before running: `docs/IMPROVEMENT_PLAN.md`, "
         "«Registered 23-10-2026, before any run: R3». Hit rate in % (95 % interval resampling diseases; candidates) of "
         "the shown candidates (extensions or shared genes, top 25) that the rule hides.\n",
         f"Sources: {S['mondo']}; {S['chembl']} ATC codes. Class terms: "
         + ", ".join(f"{k} {v}" for k, v in S["roots"].items()) + (f"; not found: {', '.join(S['missing'])}" if S["missing"] else "")
         + f". Website diseases with one class: " + ", ".join(f"{k} {v}" for k, v in S["website_diseases_one_class"].items())
         + f" ({S['website_diseases_several_classes']} with several, left alone). Drugs with an anti-infective class: "
         f"{S['drugs_with_a_class']} (" + ", ".join(f"{k} {v}" for k, v in S["drugs_per_class"].items()) + ").\n",
         "Test diseases with one class: " + "; ".join(f"{g} " + ", ".join(f"{k} {v}" for k, v in d.items())
                                                      for g, d in out["infectious_test_diseases"].items()) + ".\n",
         "| Set | Removed from the shown sections |", "|---|---|"]
    for grp in ("benchmark", "areas", "external"):
        L.append(f"| {grp} | {fmt(R.get(f'{grp}|removed'))} |")
    approved = [p for p in out["pairs"] if p["approved"]]
    informative = [g for g in ("benchmark", "areas") if inf(g)[3] >= 20]
    below = all(inf(g)[0] < 0.05 for g in informative) and (len(informative) == 2 or inf("external")[0] < 0.05)
    ok = bool(below and not approved and any(inf(g)[3] for g in ("benchmark", "areas", "external")))
    L += ["", f"Informative sets (≥ 20 removed candidates): {', '.join(informative) or 'none'}; removed candidates below "
              f"5 % where required: {'yes' if below else 'no'}. Approved indications among the removed pairs: "
              f"**{len(approved)}**.\n",
          f"**R3 decision:** {'adopted' if ok else 'not adopted'}.\n", "Removed pairs (manual check):\n",
          "| Set | Disease (class) | Drug (classes) | Correct | Approved |", "|---|---|---|---|---|"]
    seen = set()
    for p in out["pairs"]:
        k = (p["set"], p["disease"], p["drug"])
        if k in seen:
            continue
        seen.add(k)
        L.append(f"| {p['set']} | {p['disease']} ({p['class']}) | {p['drug']} ({', '.join(p['drug_classes'])}) | "
                 f"{'yes' if p['hit'] else ''} | {'**yes**' if p['approved'] else ''} |")
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "R3_INFECTIONS.md").write_text(text, "utf-8")
    print(text[:8000])


if __name__ == "__main__":
    report() if sys.argv[1:] == ["report"] else main()
