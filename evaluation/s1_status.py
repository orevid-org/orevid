"""S1 (docs/IMPROVEMENT_PLAN.md, «Registered 08-11-2026: S1, R6b, R8b»): the status shown for drugs that DrugBank
calls «experimental», «investigational», «withdrawn» or «unknown» becomes «approved in some country» when another of
the four sources of evaluation/approval.py says they are approved. This lists the corrections and draws the random
sample of 20 to check against an independent public source (criterion: at least 18 confirmed).

    py -3 -m evaluation.s1_status     # -> docs/S1_APPROVAL_STATUS.md (the check is filled in by hand)
"""
import collections
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
RELABEL = ("experimental", "investigational", "withdrawn", "unknown")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from graph import Graph
    from predictor import drug_status
    from evaluation.approval import approved_somewhere
    G = Graph()
    status = drug_status(G)
    ok = approved_somewhere(G)
    fixed = {int(f): (s, ok[int(f)]) for f, s in status.items() if s in RELABEL and int(f) in ok}
    shown = collections.Counter()
    for fj in sorted((ROOT / "web" / "public" / "data" / "d").glob("*.json")):
        for v in json.loads(fj.read_text("utf-8")).values():
            for sec in ("extensions", "candidates", "no_use"):
                for c in v.get(sec) or []:
                    shown[c["name"]] += 1
    names = {f: G.name(f) for f in fixed}
    on_pages = {f for f in fixed if shown[names[f]]}
    rng = np.random.default_rng(0)
    pool = sorted(on_pages)
    sample = [pool[i] for i in rng.choice(len(pool), min(20, len(pool)), replace=False)]
    by = collections.Counter(s for s, _ in fixed.values())
    L = ["# S1. Approval status from four sources\n",
         "Generated by `py -3 -m evaluation.s1_status`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 08-11-2026: S1, "
         "R6b, R8b».\n",
         f"Drugs whose DrugBank status would be corrected to «approved in some country»: {len(fixed):,} "
         f"({', '.join(f'{k} {n}' for k, n in by.most_common())}); of them on the website pages: {len(on_pages):,} "
         f"({sum(shown[names[f]] for f in on_pages):,} entries).\n",
         "## Random sample of 20 (drugs on the pages), checked against an independent public source\n",
         "| Drug | DrugBank | Sources saying approved | Independent check |", "|---|---|---|---|"]
    L += [f"| {names[f]} | {fixed[f][0]} | {', '.join(fixed[f][1])} | (to fill) |" for f in sample]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "S1_APPROVAL_STATUS.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
