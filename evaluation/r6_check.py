"""Validation of R6 (docs/IMPROVEMENT_PLAN.md, «Registered 08-11-2026: R6»): drugs never approved (DrugBank
«experimental»), withdrawn everywhere («withdrawn» without «approved») or non-active in both the US and the EU (current
status table, P55) are not shown as direct extensions or candidates. Criteria fixed before running: the removed shown
entries must hit below 5 % on the benchmark (zero-shot seeds 1-5) and on the nine areas (top 25 per disease, sections
as evaluation/evidence_ci.py); external exam reported; manual check of the 20 most frequently removed drugs.

    py -3 -m evaluation.r6_check     # -> docs/R6_UNAVAILABLE_DRUGS.md
"""
import collections
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent


def unavailable_drugs(variant="a"):
    """{drug node: reason} for R6 (variant «a») or R6b (variant «b»: never approved by any of the four sources of
    evaluation/approval.py; no US/EU part)."""
    from graph import Graph
    from predictor import drug_status
    from web.build import label_tables
    G = Graph()
    status = drug_status(G)
    if variant == "b":
        from evaluation.approval import approved_somewhere
        ok = approved_somewhere(G)
        return {int(f): f"DrugBank {s}, approved by no other source" for f, s in status.items()
                if s in ("experimental", "withdrawn") and int(f) not in ok}
    _, now = label_tables()
    out = {}
    for f, s in status.items():
        if s == "experimental":
            out[int(f)] = "never approved (DrugBank experimental)"
        elif s == "withdrawn":
            out[int(f)] = "withdrawn (DrugBank, not approved anywhere)"
    for f, v in now.items():
        if "us" in v and "eu" in v and int(f) not in out:
            out[int(f)] = f"US {v['us']}, EU {v['eu']}"
    return out


def task_rates(t, gn, bad):
    T = gn.table("base")
    g = t["g"]
    out = {"removed": [0, 0], "kept": [0, 0]}
    for c in range(len(t["D"])):
        for j in t["top"][c]:
            if not (t["V"][j, c] or T[j, c]):
                continue
            k = "removed" if int(g.drugs[j]) in bad else "kept"
            out[k][0] += int(t["hits"][c][j])
            out[k][1] += 1
    return out


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.evidence_ci import Genes, bench_task, external_task
    from evaluation.txgnn import AREAS, load_kg, node_types
    variant = "b" if "b" in sys.argv[1:] else "a"
    bad = unavailable_drugs(variant)
    print(f"unavailable drugs: {len(bad)}", collections.Counter(r.split(" (")[0].split(",")[0] for r in bad.values()), flush=True)
    kg = load_kg()
    types = node_types(kg)
    res = {}
    for name, tasks in {"benchmark": [("complex_disease", s) for s in (1, 2, 3, 4, 5)],
                        "areas": [(a, 1) for a in AREAS]}.items():
        tot = {"removed": [0, 0], "kept": [0, 0]}
        for split, seed in tasks:
            t = bench_task(kg, types, split, seed)
            r = task_rates(t, Genes(t["g"], t["D"]), bad)
            for k in tot:
                tot[k] = [tot[k][0] + r[k][0], tot[k][1] + r[k][1]]
            print(f"  {name} {split} {seed}: {r}", flush=True)
        res[name] = tot
    t = external_task(kg, types)
    res["external"] = task_rates(t, Genes(t["g"], t["D"]), bad)
    print(res, flush=True)

    # website: shown entries that R6 removes
    from graph import Graph
    G = Graph()
    by_name = collections.defaultdict(list)
    for x in np.flatnonzero(G.types == "drug"):
        by_name[G.name(int(x))].append(int(x))
    removed, pages = collections.Counter(), set()
    for fj in sorted((ROOT / "web" / "public" / "data" / "d").glob("*.json")):
        for k, v in json.loads(fj.read_text("utf-8")).items():
            for sec in ("extensions", "candidates"):
                for c in v.get(sec) or []:
                    if any(f in bad for f in by_name.get(c["name"], [])):
                        removed[c["name"]] += 1
                        pages.add(k)
    reason = {G.name(f): r for f, r in bad.items()}

    rate = lambda x: f"{100 * x[0] / x[1]:.1f} % ({x[0]} of {x[1]})" if x[1] else "– (0)"
    ok = all(res[n]["removed"][1] == 0 or res[n]["removed"][0] / res[n]["removed"][1] < 0.05 for n in ("benchmark", "areas"))
    L = ["# R6. Drugs never approved, or withdrawn everywhere we can tell\n",
         "Generated by `py -3 -m evaluation.r6_check`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 08-11-2026: R6».\n",
         f"Drugs covered by the rule: {len(bad):,}.\n",
         "## Hit rate of shown entries (direct extensions and shared-genes candidates) in the top 25\n",
         "| Test | Removed by R6 | Kept |", "|---|---|---|"]
    L += [f"| {n} | {rate(res[n]['removed'])} | {rate(res[n]['kept'])} |" for n in ("benchmark", "areas", "external")]
    L += ["", f"**Hit-rate criterion (removed < 5 % on benchmark and areas): {'met' if ok else 'NOT met'}.**\n",
          "## Website\n", f"Shown entries removed: {sum(removed.values()):,} on {len(pages):,} pages.\n",
          "The 20 most frequently removed drugs, for the manual check:\n", "| Drug | Pages | Reason |", "|---|---|---|"]
    L += [f"| {n} | {k} | {reason.get(n, '?')} |" for n, k in removed.most_common(20)]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / ("R6B_NEVER_APPROVED.md" if variant == "b" else "R6_UNAVAILABLE_DRUGS.md")).write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
