"""T1: did the candidates OREVID showed meet their primary endpoint more often in posted trials? (docs/IMPROVEMENT_PLAN.md,
«Registered 23-10-2026, evening: T1»; trials from sources/ctgov.py, lists from the frozen snapshot of 12-10-2026,
data/snapshot/2026-10-12/ranking_top100.csv.gz).

Groups per disease: shown (website sections extension / candidate), ranked 1–25 and not shown, ranks 26–100. A pair is
«met» if any of its trials met its primary endpoint, «not met» if its trials have primary analyses and none met.

    py -3 -m evaluation.t1_trials     # -> data/eval/t1_trials.json, docs/T1_TRIALS.md
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
B = 5000


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.twins import twins
    from graph import INDICATION, Graph
    g = Graph()
    tw = twins(g, "disease")
    t = pd.read_parquet(ROOT / "data" / "ext" / "ctgov_trials.parquet")
    t = t[t.outcome != "unknown"]
    outcome = {}
    for f, d, o, ph in zip(t.drug, t.disease, t.outcome, t.phase):
        for d2 in tw.get(int(d), {int(d)}):
            k = (int(f), d2)
            prev = outcome.get(k, (False, set()))
            outcome[k] = (prev[0] or o == "met", prev[1] | {ph})
    r = pd.read_csv(ROOT / "data" / "snapshot" / "2026-10-12" / "ranking_top100.csv.gz",
                    usecols=["disease_node", "rank", "drug_node", "website_section"])
    r["group"] = np.where(r.website_section.isin(["extension", "candidate"]), "shown",
                          np.where(r["rank"] <= 25, "ranked 1–25, not shown", "ranks 26–100"))
    I = g.M(INDICATION).tocsr()
    ot = pd.read_parquet(ROOT / "data" / "ext" / "ot_approvals.parquet")
    approved = set(zip(ot[ot.status == "confirmed"].x_index.astype(int), ot[ot.status == "confirmed"].y_index.astype(int)))
    keys = list(zip(r.drug_node.astype(int), r.disease_node.astype(int)))
    r["met"] = [outcome[k][0] if k in outcome else None for k in keys]
    r["phases"] = ["|".join(sorted(outcome[k][1])) if k in outcome else "" for k in keys]
    r["approved"] = [d in set(I.indices[I.indptr[f]:I.indptr[f + 1]].tolist()) or (f, d) in approved for f, d in keys]
    x = r[r.met.notna()].copy()
    x["met"] = x.met.astype(bool)
    rng = np.random.default_rng(0)

    def diff(sub, a, b):
        per = sub.groupby(["disease_node", "group"]).met.agg(["sum", "size"]).unstack(fill_value=0)
        dis = per.index.to_numpy()
        ha, na = per["sum"].get(a, 0 * per["size"].iloc[:, 0]).to_numpy(float), per["size"].get(a, 0 * per["size"].iloc[:, 0]).to_numpy(float)
        hb, nb = per["sum"].get(b, 0 * per["size"].iloc[:, 0]).to_numpy(float), per["size"].get(b, 0 * per["size"].iloc[:, 0]).to_numpy(float)
        idx = rng.integers(0, len(dis), (B, len(dis)))
        d = ha[idx].sum(1) / np.maximum(na[idx].sum(1), 1) - hb[idx].sum(1) / np.maximum(nb[idx].sum(1), 1)
        return [float(ha.sum() / max(na.sum(), 1) - hb.sum() / max(nb.sum(), 1)), float(np.percentile(d, 2.5)),
                float(np.percentile(d, 97.5))]

    def table(sub):
        return {gname: {"pairs": int(len(s)), "met": int(s.met.sum()), "share": float(s.met.mean()) if len(s) else None}
                for gname, s in sub.groupby("group")}

    res = {"trials_with_outcome": int(t.nct.nunique()), "pairs": table(x),
           "shown_minus_not_shown": diff(x, "shown", "ranked 1–25, not shown"),
           "shown_minus_low": diff(x, "shown", "ranks 26–100"),
           "not_approved": {"pairs": table(x[~x.approved]),
                            "shown_minus_not_shown": diff(x[~x.approved], "shown", "ranked 1–25, not shown")},
           "by_phase": {ph: table(x[x.phases.str.contains(ph)]) for ph in ("PHASE2", "PHASE3")}}
    res["claim"] = bool(res["shown_minus_not_shown"][1] > 0)
    (ROOT / "data" / "eval" / "t1_trials.json").write_text(json.dumps(res, indent=1), "utf-8")
    f = lambda v: f"{100 * v[0]:+.1f} ({100 * v[1]:+.1f} to {100 * v[2]:+.1f})"
    L = ["# T1. Posted trial outcomes of the candidates OREVID showed\n",
         "Generated by `py -3 -m evaluation.t1_trials`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 23-10-2026, evening: "
         "T1». Trials: ClinicalTrials.gov API v2, phase 2–3 with posted results, one drug, primary outcome met (p < 0.05 in an "
         "analysis) or not; lists: the frozen snapshot of 12-10-2026. Differences in percentage points, 95 % interval "
         "resampling diseases.\n",
         f"Trials with a met / not-met primary outcome: {res['trials_with_outcome']:,}.\n",
         "| Group | Pairs with a trial | Met | Share met |", "|---|---|---|---|"]
    for k in ("shown", "ranked 1–25, not shown", "ranks 26–100"):
        v = res["pairs"].get(k)
        if v:
            L.append(f"| {k} | {v['pairs']} | {v['met']} | {100 * v['share']:.1f} % |")
    L += ["", f"Shown − ranked and not shown (deciding): {f(res['shown_minus_not_shown'])}; shown − ranks 26–100: "
              f"{f(res['shown_minus_low'])}. Without approved indications: shown − not shown "
              f"{f(res['not_approved']['shown_minus_not_shown'])}.\n",
          f"**Decision:** {'claim supported' if res['claim'] else 'claim not supported'}.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "T1_TRIALS.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
