"""F1 (display only) and G3's display: compute the framing fields of every built page (web/framing.py), draw the
registered check samples, and, once the checks pass, write the fields into the built pages (no rebuild: no candidate is
added, removed or reordered). A full rebuild gives the same fields (web/build.py calls web.framing.frame).

    py -3 -m evaluation.f1_apply sample   # -> data/eval/f1_frames.pkl, docs/F1_FEATURE_FRAMING.md (checks to fill by hand)
    py -3 -m evaluation.f1_apply apply    # writes the fields that passed their check into web/public/data/d/*.json
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "web" / "public" / "data" / "d"
PKL = ROOT / "data" / "eval" / "f1_frames.pkl"


def load_pages():
    pages = {}
    for fj in sorted(DEST.glob("*.json")):
        pages.update({int(k): v for k, v in json.loads(fj.read_text("utf-8")).items()})
    return pages


def compute():
    from graph import Graph
    from evaluation.twins import twins
    from web.framing import Framing, frame
    g = Graph()
    F = Framing(g)
    tw = twins(g, "disease")
    pages = load_pages()
    ids = set(pages)
    frames = {}
    for k, d in enumerate(sorted(pages)):
        frames[d] = frame(F, d, tw.get(d, {d}), pages[d], lambda x: x in ids)
        if (k + 1) % 1000 == 0:
            print(f"  {k + 1}/{len(pages)}", flush=True)
    pd.to_pickle(frames, PKL)
    return pages, frames


def proposals_from(page, via):
    """Names of the shown proposals that come from the via disease `via`."""
    from web.build import valid_similar
    out = [c["name"] for c in page.get("extensions") or [] if isinstance(c, dict) and via in (c.get("neighbour_diseases") or [])]
    for c in page.get("candidates") or []:
        for e in c.get("expl") or []:
            if (e.get("t") == "neighbour" and via in e["m"]) or (
                    e.get("t") == "similar" and any(m[0] == via and valid_similar(m) for m in e["m"])):
                out.append(c["name"])
                break
    return out


def sample():
    sys.stdout.reconfigure(encoding="utf-8")
    pages, frames = compute()
    rng = np.random.default_rng(1)
    labels = [(pages[d]["name"], via, hp, hpn, route, ", ".join(proposals_from(pages[d], via)[:3]))
              for d, f in frames.items() for via, (hp, hpn, route) in f["features"].items()]
    unlabelled = [(pages[d]["name"], c["name"], n) for d, f in frames.items() for c in pages[d].get("extensions") or []
                  if isinstance(c, dict) for n in (c.get("neighbour_diseases") or [])[:1] if n not in f["features"]]
    trials = [(pages[d]["name"], drug, r[0], r[1], r[2]) for d, f in frames.items()
              for drug, recs in f["trial_conditions"].items() for r in recs if r[0] != "+"]
    pick = lambda xs: [xs[i] for i in rng.choice(len(xs), min(20, len(xs)), replace=False)] if xs else []
    s_lab, s_unl, s_tri = pick(labels), pick(unlabelled), pick(trials)
    n_merged = sum(bool(f["merged"]) for f in frames.values())
    n_fp = sum(bool(f["feature_pages"]) for f in frames.values())
    by_route = pd.Series([x[4] for x in labels]).value_counts().to_dict() if labels else {}
    groups = pd.DataFrame([{k: v["n"] for k, v in f["genes_by_source"].items()} for f in frames.values()]).fillna(0)
    L = ["# F1. Proposals framed by the feature they treat (display only), and G3's gene display\n",
         "Generated by `py -3 -m evaluation.f1_apply sample`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 09-11-2026, "
         "on the work PC, before any run: G3 … and F1 …» (amendment of 09-11 on the F1a route). No candidate is added, "
         "removed or reordered.\n", "## Coverage\n",
         f"- Pages: {len(pages):,}.",
         f"- F1a «for a feature of this disease»: {len(labels):,} (page, source disease) labels on "
         f"{sum(bool(f['features']) for f in frames.values()):,} pages; by route: "
         + ", ".join(f"{k} {v:,}" for k, v in by_route.items()) + ".",
         f"- F1b trials with their registered condition: {len(trials):,} trial entries on "
         f"{sum(bool(f['trial_conditions']) for f in frames.values()):,} pages.",
         f"- F1c: {n_merged:,} pages merge several MONDO terms; {n_fp:,} pages link to diseases that are HPO phenotypes "
         "of the page disease (NF1 → MPNST).",
         "- G3 display, genes by strongest source (pages with the group; genes): " + ", ".join(
             f"{k} {int((groups[k] > 0).sum()):,} ({int(groups[k].sum()):,})" for k in groups.columns) + ".\n",
         "## F1a check 1: 20 random «feature» labels (criterion: at least 18 right)\n",
         "| Page | Source disease | HPO phenotype of the page | Route | Proposals from it | Right? |", "|---|---|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} {d} | {e} | {f} | (to fill) |" for a, b, c, d, e, f in s_lab]
    L += ["", "## F1a check 2: 20 random extensions not labelled as a feature (criterion: at most 2 should have been)\n",
          "| Page | Extension | Source disease | Should it be a feature? |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | (to fill) |" for a, b, c in s_unl]
    L += ["", "## F1b check: 20 random trials (criterion: the shown condition matches ClinicalTrials.gov in all 20)\n",
          "| Page | Drug | Trial | Phase | Condition shown | ClinicalTrials.gov |", "|---|---|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d} | {e} | (to fill) |" for a, b, c, d, e in s_tri]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "F1_FEATURE_FRAMING.md").write_text(text, "utf-8")
    print(text)


def apply(parts):
    """parts: subset of {"genes_by_source", "features", "trial_conditions", "merged", "feature_pages"}."""
    sys.stdout.reconfigure(encoding="utf-8")
    frames = pd.read_pickle(PKL)
    n = 0
    for fj in sorted(DEST.glob("*.json")):
        pages = json.loads(fj.read_text("utf-8"))
        for k, v in pages.items():
            f = frames.get(int(k))
            if f is None:
                continue
            for p in parts:
                if f[p]:
                    v[p] = f[p]
                else:
                    v.pop(p, None)
            n += 1
        fj.write_text(json.dumps(pages, ensure_ascii=False, separators=(",", ":"), allow_nan=False), "utf-8")
    print(f"pages updated: {n:,}; fields: {', '.join(parts)}")


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["apply"]:
        apply(a[1:] or ["genes_by_source", "features", "trial_conditions", "merged", "feature_pages"])
    else:
        sample()
