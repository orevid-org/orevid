"""How much of the advantage is biology and how much is «knowing which drugs are already used»?

Uses the scores saved by evaluation/txgnn.py (data/eval/scores/) and measures the ranking again
with three different candidate sets:

  A. approved:        only drugs with some indication in training (candidates and positives).
  B. no blockbusters: the 10 % of drugs with the most indications (blockbusters such as the
                      corticosteroids) are removed, from the candidates and from the positives.
  C. no prior use:    only the positives that had no indication in training count; the other
                      positives are removed from the list.

    py -3 -m evaluation.novelty
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from evaluation.txgnn import CACHE, AREAS

MODELS = {"popularity": "Popularity", "graph_only_model": "Ours without popularity",
          "gbm_+_masked_training": "Ours", "LambdaRank_+_masked": "Ours (ranking)",
          "TxGNN_run_here": "TxGNN"}
NAMES = {"complex_disease": "Zero-shot (5 seeds)", "cell_proliferation": "Cancer", "mental_health": "Mental health",
         "cardiovascular": "Cardiovascular", "anemia": "Anaemia", "adrenal_gland": "Adrenal",
         "autoimmune": "Autoimmune", "metabolic_disorder": "Metabolic", "diabetes": "Diabetes",
         "neurodigenerative": "Neurodegenerative"}


def measure(s, pos, cand, k=100, rng=None):
    """Recall@k, Precision@K and mean rank of the positives among the candidates (ties at random)."""
    pos = np.intersect1d(pos, np.flatnonzero(cand))
    if not len(pos):
        return None
    idx = np.flatnonzero(cand)
    v = s[idx] + rng.random(len(idx)) * 1e-9 * (np.abs(s[idx]).max() + 1e-9)
    order = idx[np.argsort(-v)]
    rank = np.empty(len(idx))
    rank[np.argsort(-v)] = np.arange(len(idx))
    pos_rank = rank[np.searchsorted(idx, pos)]
    return {"Recall@100": np.mean(pos_rank < k), "Precision@K": np.mean(pos_rank < len(pos)),
            "Avg Rank": 1 - np.mean(pos_rank) / len(idx), "positives": len(pos)}


def analyse(f):
    z = np.load(f, allow_pickle=True)
    degree, positives = z["degree"], list(z["positives"])
    n = len(degree)
    approved = degree > 0
    threshold = np.quantile(degree[approved], 0.9)
    blockbuster = degree >= threshold
    res = []
    rng = np.random.default_rng(0)
    for model_key in MODELS:
        if model_key not in z:
            continue
        S = z[model_key]
        for c, pos in enumerate(positives):
            pos = np.asarray(pos, int)
            others = np.zeros(n, bool)
            others[pos[degree[pos] > 0]] = True
            scenarios = {
                "A. approved": (S[:, c], pos, approved),
                "B. no blockbusters": (S[:, c], pos, ~blockbuster),
                "C. no prior use": (S[:, c], pos[degree[pos] == 0], ~others),
            }
            for sc, (s, p, cand) in scenarios.items():
                m = measure(s, p, cand, rng=rng)
                if m:
                    res.append({"model": MODELS[model_key], "scenario": sc, **m})
    return pd.DataFrame(res), int(approved.sum()), float(threshold)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    suffix = sys.argv[1] if len(sys.argv) > 1 else "extra_no_ctd_r5_rank"
    files = sorted((CACHE / "scores").glob(f"*_{suffix}.npz"))
    tables = []
    for f in files:
        split = next(s for s in ["complex_disease"] + AREAS if f.name.startswith(s))
        d, n_appr, threshold = analyse(f)
        d["split"] = NAMES[split]
        tables.append(d)
    all_ = pd.concat(tables)
    order = [m for m in ["Popularity", "TxGNN", "Ours without popularity", "Ours", "Ours (ranking)"]
             if m in set(all_.model)]
    L = ["# Novelty tests\n",
         "Generated by `evaluation/novelty.py` from the same splits and scores as the comparison with "
         "TxGNN. Mean per disease (zero-shot: 5 seeds together; areas: all the areas together).\n",
         "- **A. Approved**: only drugs with some known indication (~1,700 candidates).",
         f"- **B. No blockbusters**: the 10 % of drugs with the most indications (≥ {threshold:.0f}) are removed, from candidates and positives.",
         "- **C. No prior use**: only the good drugs without any other indication count; the other good ones are removed.\n"]
    for group, mask in [("Zero-shot", all_["split"].str.startswith("Zero")), ("Disease areas", ~all_["split"].str.startswith("Zero"))]:
        d = all_[mask]
        L.append(f"## {group}\n")
        L.append("| Scenario | Metric | " + " | ".join(order) + " |")
        L.append("|---|---|" + "---|" * len(order))
        for sc in sorted(d.scenario.unique()):
            e = d[d.scenario == sc]
            n = int(e[e.model == "Ours"].shape[0])
            for m in ["Recall@100", "Precision@K", "Avg Rank"]:
                v = e.groupby("model")[m].mean().reindex(order)
                best = v.drop("Popularity").idxmax()
                cell = [f"**{x:.2f}**" if k == best else f"{x:.2f}" for k, x in v.items()]
                L.append(f"| {sc} ({n} diseases) | {m} | " + " | ".join(cell) + " |")
        L.append("")
    # per area, scenario C (the most demanding)
    L.append("## No prior use, per split (Recall@100)\n")
    L.append("| Split | Diseases | " + " | ".join(order) + " |")
    L.append("|---|---|" + "---|" * len(order))
    e = all_[all_.scenario == "C. no prior use"]
    for p_ in e["split"].unique():
        v = e[e["split"] == p_].groupby("model")["Recall@100"].mean().reindex(order)
        n = int((e[(e["split"] == p_) & (e.model == "Ours")]).shape[0])
        L.append(f"| {p_} | {n} | " + " | ".join(f"{x:.2f}" for x in v) + " |")
    dest = Path(__file__).resolve().parent.parent / "docs" / ("NOVELTY.md" if suffix == "extra_no_ctd_r5_rank" else f"NOVELTY_{suffix}.md")
    dest.write_text("\n".join(L) + "\n", "utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
