"""O2: do the drugs approved for a cancer lineage kill its cell lines better in PRISM? (docs/IMPROVEMENT_PLAN.md,
«Registered 23-10-2026, evening, before any download: O2»; data from sources/prism.py, lineages in
resources/prism_lineages.csv written before any AUC was read).

    py -3 -m evaluation.o2_prism      # -> data/eval/o2_prism.json, docs/O2_PRISM.md
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parent.parent
B = 5000


def lineage_diseases(g):
    """lineage -> graph disease nodes (the table's cancers, their descendants and twins)."""
    from evaluation.twins import twins
    from sources.hierarchy import load
    t = pd.read_csv(ROOT / "resources" / "prism_lineages.csv", comment="#")
    names = {g.name(int(i)).lower(): int(i) for i in np.flatnonzero(g.types == "disease") if g.origin[int(i)] == "PrimeKG"}
    h = load()
    kids = defaultdict(list)
    for p, c in zip(h.parent.astype(int), h.child.astype(int)):
        kids[p].append(c)
    tw = twins(g, "disease")
    out = {}
    for lin, sub in t.groupby("lineage"):
        seen, stack = set(), [names[n.lower()] for n in sub.disease if n.lower() in names]
        while stack:
            x = stack.pop()
            if x not in seen:
                seen.add(x)
                stack += kids.get(x, [])
        out[lin] = set().union(*(tw.get(x, {x}) for x in seen)) if seen else set()
    return out


def boot(v, rng):
    v = np.asarray(v, float)
    m = rng.choice(v, (B, len(v))).mean(axis=1)
    return float(v.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from graph import INDICATION, Graph
    g = Graph()
    p = pd.read_parquet(ROOT / "data" / "ext" / "prism_lineage.parquet")
    p = p.groupby(["drug", "lineage"]).auc.median().reset_index()
    I = g.M(INDICATION).tocsr()
    ot = pd.read_parquet(ROOT / "data" / "ext" / "ot_approvals.parquet")
    ot = ot[ot.status == "confirmed"]
    approved = defaultdict(set)
    for f in p.drug.unique():
        approved[int(f)] |= set(I.indices[I.indptr[f]:I.indptr[f + 1]].tolist())
    for f, d in zip(ot.x_index.astype(int), ot.y_index.astype(int)):
        approved[f].add(d)
    lin_d = lineage_diseases(g)
    overall = p.groupby("drug").auc.median()
    rows = []
    for lin, sub in p.groupby("lineage"):
        D = lin_d.get(lin, set())
        y = np.array([bool(approved[int(f)] & D) for f in sub.drug])
        if not y.any() or y.all():
            continue
        raw = roc_auc_score(y, -sub.auc.to_numpy())
        rel = roc_auc_score(y, -(sub.auc.to_numpy() - overall.loc[sub.drug].to_numpy()))
        rows.append({"lineage": lin, "drugs": int(len(sub)), "approved": int(y.sum()), "auroc": float(raw),
                     "auroc_relative": float(rel), "diseases": len(D)})
    rng = np.random.default_rng(0)
    r = pd.DataFrame(rows)
    res = {"lineages": rows, "auroc": boot(r.auroc, rng), "auroc_relative": boot(r.auroc_relative, rng),
           "drugs": int(p.drug.nunique())}
    res["passes"] = bool(res["auroc"][1] > 0.5)
    (ROOT / "data" / "eval" / "o2_prism.json").write_text(json.dumps(res, indent=1), "utf-8")
    f3 = lambda x: f"{x[0]:.3f} ({x[1]:.3f}–{x[2]:.3f})"
    L = ["# O2. PRISM drug sensitivity by cancer lineage\n",
         "Generated by `py -3 -m evaluation.o2_prism`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 23-10-2026, evening, "
         "before any download: O2». PRISM Repurposing 19Q4 secondary screen (CC BY 4.0), median AUC per drug and lineage; "
         "positives = screened drugs approved (PrimeKG or confirmed Open Targets) for a cancer of the lineage "
         "(`resources/prism_lineages.csv`, with descendants). AUROC of −AUC; mean over lineages, 95 % interval resampling "
         "lineages.\n",
         f"Screened drugs mapped to the graph: {res['drugs']:,}; lineages with positives: {len(rows)}.\n",
         "| Score | Mean AUROC (95 % CI) |", "|---|---|",
         f"| −AUC in the lineage (registered, deciding) | {f3(res['auroc'])} |",
         f"| −(AUC in the lineage − the drug's median AUC over all lineages) (reported: lineage specificity) | {f3(res['auroc_relative'])} |",
         "", "| Lineage | Drugs | Approved | AUROC | AUROC, relative |", "|---|---|---|---|---|"]
    L += [f"| {x['lineage']} | {x['drugs']} | {x['approved']} | {x['auroc']:.3f} | {x['auroc_relative']:.3f} |" for x in rows]
    L += ["", f"**Decision:** {'passes → a feature test is to be registered' if res['passes'] else 'does not pass'}.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "O2_PRISM.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
