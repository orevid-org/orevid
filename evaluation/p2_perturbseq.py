"""P2: does knocking down the genes a drug inhibits reverse the disease's expression signature? (docs/IMPROVEMENT_PLAN.md,
«Registered 23-10-2026, evening, before any download: P2»; knockdowns from sources/perturbseq.py, disease signatures
CREEDS as P45). Gate as P1b (benchmark and temporal 2015 no-prior-use positives against random); for the ranking a
missing score counts as 0 (neutral).

    py -3 -m evaluation.p2_perturbseq    # -> data/eval/p2_gate.json, docs/P2_PERTURBSEQ.md
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
GATE = ROOT / "data" / "eval" / "p2_gate.json"


class Knockdown:
    def __init__(self):
        from evaluation.lincs_reversal import disease_signatures
        from evaluation.m1_direction import drug_actions
        from graph import Graph
        full = Graph()
        p = pd.read_parquet(ROOT / "data" / "ext" / "perturbseq.parquet")
        self.kd = defaultdict(lambda: (set(), set()))
        for k, gene, d in zip(p.knockdown, p.gene, p.direction):
            self.kd[int(k)][0 if d == "up" else 1].add(int(gene))
        sym_node = {str(s).upper(): int(k) for k, s, t in zip(full.nodes.node_index, full.nodes.node_name, full.nodes.node_type)
                    if t == "gene/protein"}
        sig, _, _, _ = disease_signatures(full)
        self.dis = {d: [({sym_node[s] for s in u if s in sym_node}, {sym_node[s] for s in dn if s in sym_node}) for u, dn in lst]
                    for d, lst in sig.items()}
        self.lowers = {f: [gn for gn, a in t.items() if a < 0 and gn in self.kd] for f, t in drug_actions(full).items()}
        self.lowers = {f: v for f, v in self.lowers.items() if v}
        self.n_drugs, self.n_pairs = len(self.lowers), sum(map(len, self.lowers.values()))

    def score(self, f, d):
        vals = []
        for gn in self.lowers.get(f, ()):
            ku, kdn = self.kd[gn]
            for du, dd in self.dis[d]:
                vals.append(len(du & kdn) + len(dd & ku) - len(du & ku) - len(dd & kdn))
        return float(np.mean(vals)) if vals else 0.0

    def for_graph(self, g):
        drugs = np.asarray(g.drugs)
        outer = self

        class Col:
            n_drugs, n_pairs = outer.n_drugs, outer.n_pairs

            def column(self, diseases):
                out = np.zeros((len(drugs), len(diseases)), np.float32)
                for c, d in enumerate(diseases):
                    if int(d) in outer.dis:
                        for j, f in enumerate(drugs):
                            if int(f) in outer.lowers:
                                out[j, c] = outer.score(int(f), int(d))
                return out
        return Col()


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.p1_offtargets import gate_sets
    K = Knockdown()
    res = gate_sets(K.for_graph)
    res["diseases_with_signature"] = len(K.dis)
    GATE.write_text(json.dumps(res, indent=1), "utf-8")
    f3 = lambda x: f"{x[0]:.3f} ({x[1]:.3f}–{x[2]:.3f})"
    fd = lambda x: "—" if not x else f"{x[0]:+.3f} ({x[1]:+.3f} to {x[2]:+.3f})"
    L = ["# P2. Perturb-seq knockdown reversal\n",
         "Generated by `py -3 -m evaluation.p2_perturbseq`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 23-10-2026, evening, "
         "before any download: P2». Knockdown signatures: Replogle et al. 2022 K562 genome-wide Perturb-seq (pseudo-bulk, top 100 "
         "up / down genes); disease signatures: CREEDS; score = mean reversal over the drug's lowered targets.\n",
         f"Drugs with a lowered, knocked-down target: {K.n_drugs:,} ({K.n_pairs:,} drug–target pairs); diseases with a "
         f"signature: {len(K.dis):,}.\n", "| Set | Diseases | Score | Random | Difference |", "|---|---|---|---|---|"]
    for k in ("benchmark", "temporal"):
        x = res[k]
        L.append(f"| {k} | {x['diseases']} | {f3(x['feature']) if x['feature'] else '—'} | "
                 f"{f3(x['random']) if x['random'] else '—'} | {fd(x['difference'])} |")
    L += ["", f"**Gate:** {'passes → model test' if res['passes'] else 'does not pass on either set; not adopted'}.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "P2_PERTURBSEQ.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
