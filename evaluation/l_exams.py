"""L1 and L2 exams (docs/IMPROVEMENT_PLAN.md, «Registered 24-10-2026: L1–L6»): does the production model rank
indications that only DrugCentral / MED-RT know (L1), and EMA orphan designations (L2), above popularity?

Positives: pairs that are neither PrimeKG indications nor confirmed Open Targets approvals (twins included). L1
candidates: approved drugs not indicated for the disease (as O1); L2 candidates: every graph drug not indicated for it,
because most designated drugs are not approved yet. Recall@100 per disease, paired difference resampling diseases.

    py -3 -m evaluation.l_exams       # -> data/eval/l_exams.json, docs/L_EXAMS.md
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from evaluation.o1_civic import recall

ROOT = Path(__file__).resolve().parent.parent
B = 5000


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.twins import twins
    from graph import INDICATION
    from predictor import Predictor, drug_status
    P = Predictor()
    g = P.g
    drugs = np.asarray(g.drugs)
    pos_of = {int(f): j for j, f in enumerate(drugs)}
    status = drug_status(g)
    approved = np.array([status.get(int(f)) == "approved" for f in drugs])
    I = g.M(INDICATION).tocsr()
    ot = pd.read_parquet(ROOT / "data" / "ext" / "ot_approvals.parquet")
    ot_conf = set(zip(ot[ot.status == "confirmed"].x_index.astype(int), ot[ot.status == "confirmed"].y_index.astype(int)))
    tw = twins(g, "disease")
    rng = np.random.default_rng(0)
    cache = {}

    def known(d):
        same = tw.get(d, {d})
        return {int(f) for t in same for f in I.indices[I.indptr[t]:I.indptr[t + 1]]} | {f for (f, t) in ot_conf if t in same}

    def exam(pairs, only_approved):
        rows, n_known = [], 0
        for d, fs in pairs.groupby("disease").drug:
            d = int(d)
            kn = known(d)
            new = {int(f) for f in fs} - kn
            n_known += len({int(f) for f in fs} & kn)
            cand = approved.copy() if only_approved else np.ones(len(drugs), bool)
            cand[[pos_of[f] for f in kn if f in pos_of]] = False
            pos = {pos_of[f] for f in new if f in pos_of and cand[pos_of[f]]}
            if not pos:
                continue
            if d not in cache:
                cache[d] = P.predict(d)[1]
            rows.append({"disease": g.name(d), "positives": len(pos), "orevid": recall(cache[d], pos, cand, rng),
                         "popularity": recall(P.degree, pos, cand, rng)})
        r = pd.DataFrame(rows)
        dd = (r.orevid - r.popularity).to_numpy(float)
        bs = rng.choice(dd, (B, len(dd))).mean(axis=1)
        return {"diseases": len(r), "positives": int(r.positives.sum()), "already_known": n_known,
                "orevid": float(r.orevid.mean()), "popularity": float(r.popularity.mean()),
                "diff": [float(dd.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]}

    dc = pd.read_parquet(ROOT / "data" / "ext" / "drugcentral_relations.parquet")
    mr = pd.read_parquet(ROOT / "data" / "ext" / "medrt.parquet")
    l1 = pd.concat([dc[dc.relation == "indication"][["drug", "disease"]], mr[mr.relation == "may_treat"][["drug", "disease"]]])
    orph = pd.read_parquet(ROOT / "data" / "ext" / "orphan_ema.parquet")
    res = {"L1 DrugCentral + MED-RT indications": exam(l1, True),
           "L1 DrugCentral only": exam(dc[dc.relation == "indication"], True),
           "L1 MED-RT only": exam(mr[mr.relation == "may_treat"], True),
           "L2 EMA orphan designations": exam(orph, False),
           "L2 designations dated 2023 or later": exam(orph[orph.date >= "2023-01-01"], False)}
    # approval dates for a future temporal test
    ap = pd.read_parquet(ROOT / "data" / "ext" / "drugcentral_approvals.parquet")
    first = ap.groupby("drug").date.min()
    pkg = [(int(f), int(d)) for f in drugs for d in I.indices[I.indptr[f]:I.indptr[f + 1]]]
    res["PrimeKG indications whose drug has a DrugCentral first-approval date"] = {
        "indications": len(pkg), "dated_drug": int(sum(f in first.index for f, _ in pkg))}
    (ROOT / "data" / "eval" / "l_exams.json").write_text(json.dumps(res, indent=1), "utf-8")
    d3 = lambda x: f"{x[0]:+.3f} ({x[1]:+.3f} to {x[2]:+.3f})"
    L = ["# L1 and L2 exams: indications only DrugCentral / MED-RT know, and EMA orphan designations\n",
         "Generated by `py -3 -m evaluation.l_exams`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 24-10-2026: L1–L6». "
         "Production model (full graph, with P61) against popularity; positives are pairs not already PrimeKG indications or "
         "confirmed Open Targets approvals. L1 candidates: approved drugs; L2: every drug (most designated drugs are not "
         "approved yet).\n", "| Exam | Diseases | Positives (already known, left out) | OREVID Recall@100 | Popularity | Difference (95 % CI) |",
         "|---|---|---|---|---|---|"]
    for k, v in res.items():
        if "diff" in v:
            L.append(f"| {k} | {v['diseases']} | {v['positives']} ({v['already_known']}) | {v['orevid']:.3f} | {v['popularity']:.3f} | {d3(v['diff'])} |")
    x = res["PrimeKG indications whose drug has a DrugCentral first-approval date"]
    L += ["", f"PrimeKG indications whose drug has a DrugCentral first-approval date: {x['dated_drug']:,} of {x['indications']:,} "
              "(the drug's first approval, not the indication's: an upper bound for dating).\n",
          f"**Decisions:** L1 claim {'supported' if res['L1 DrugCentral + MED-RT indications']['diff'][1] > 0 else 'not supported'}; "
          f"L2 claim {'supported' if res['L2 EMA orphan designations']['diff'][1] > 0 else 'not supported'}.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "L_EXAMS.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
