"""O1: does the production model rank CIViC-supported cancer uses above popularity? (docs/IMPROVEMENT_PLAN.md,
«Registered 23-10-2026, evening, before any download: O1»; data from sources/civic.py).

Positives: CIViC predictive, supporting, sensitivity / response evidence of levels A–B with a single drug, for pairs
that are neither PrimeKG indications nor confirmed Open Targets approvals (twins included). For each such cancer: the
production ranking (full graph, predictor.py) of the approved drugs not indicated for it, against popularity (number
of indications). Recall@100 per disease; paired difference with a 95 % interval resampling diseases.

    py -3 -m evaluation.o1_civic       # -> data/eval/o1_civic.json, docs/O1_CIVIC.md
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
B = 5000


def recall(scores, pos, cand, rng, k=100):
    idx = np.flatnonzero(cand)
    order = idx[np.argsort(-(scores[idx] + rng.random(len(idx)) * 1e-9))]
    return len(set(order[:k].tolist()) & pos) / len(pos)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.twins import twins
    from graph import INDICATION
    from predictor import Predictor, drug_status
    P = Predictor()
    g = P.g
    status = drug_status(g)
    drugs = np.asarray(g.drugs)
    approved = np.array([status.get(int(f)) == "approved" for f in drugs])
    I = g.M(INDICATION).tocsr()
    ot = pd.read_parquet(ROOT / "data" / "ext" / "ot_approvals.parquet")
    ot_conf = set(zip(ot[ot.status == "confirmed"].x_index.astype(int), ot[ot.status == "confirmed"].y_index.astype(int)))
    clin = pd.read_parquet(ROOT / "data" / "prep" / "attributes.parquet", columns=["relation", "x_index", "y_index"])
    clin = set(zip(*clin[clin.relation == "clinical"][["x_index", "y_index"]].to_numpy().T))
    tw = twins(g, "disease")
    c = pd.read_parquet(ROOT / "data" / "ext" / "civic.parquet")
    c = c[(c.evidence_type == "Predictive") & (c.direction == "Supports") & (c.significance == "Sensitivity/Response")
          & c.level.isin(["A", "B"]) & (c.n_therapies == 1)].dropna(subset=["drug", "disease"])
    pos_of = {int(f): j for j, f in enumerate(drugs)}
    rng = np.random.default_rng(0)
    rows, n_known = [], 0
    for d, sub in c.groupby("disease"):
        d = int(d)
        same = tw.get(d, {d})
        known = {int(f) for t in same for f in I.indices[I.indptr[t]:I.indptr[t + 1]]} | {f for (f, t) in ot_conf if t in same}
        pairs = {int(f) for f in sub.drug} - known
        n_known += len({int(f) for f in sub.drug} & known)
        pos = {pos_of[f] for f in pairs if f in pos_of and approved[pos_of[f]]}
        if not pos:
            continue
        cand = approved.copy()
        cand[[pos_of[f] for f in known if f in pos_of]] = False
        _, z, _ = P.predict(d)
        new = {j for j in pos if not any((int(drugs[j]), t) in clin or (t, int(drugs[j])) in clin for t in same)}
        rows.append({"disease": g.name(d), "positives": len(pos), "orevid": recall(z, pos, cand, rng),
                     "popularity": recall(P.degree, pos, cand, rng),
                     "orevid_new": recall(z, new, cand, rng) if new else None,
                     "popularity_new": recall(P.degree, new, cand, rng) if new else None, "n_new": len(new)})
    r = pd.DataFrame(rows)

    def paired(a, b):
        m = r[a].notna()
        d = (r[a][m] - r[b][m]).to_numpy(float)
        bs = rng.choice(d, (B, len(d))).mean(axis=1)
        return [float(d.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)), int(m.sum())]

    res = {"diseases": len(r), "positives": int(r.positives.sum()), "already_known_pairs": n_known,
           "orevid": float(r.orevid.mean()), "popularity": float(r.popularity.mean()), "diff": paired("orevid", "popularity"),
           "new_positives": int(r.n_new.sum()), "orevid_new": float(r.orevid_new.dropna().mean()),
           "popularity_new": float(r.popularity_new.dropna().mean()), "diff_new": paired("orevid_new", "popularity_new"),
           "rows": rows}
    res["claim"] = bool(res["diff"][1] > 0)
    (ROOT / "data" / "eval" / "o1_civic.json").write_text(json.dumps(res, indent=1), "utf-8")
    d3 = lambda x: f"{x[0]:+.3f} ({x[1]:+.3f} to {x[2]:+.3f}; {x[3]} diseases)"
    L = ["# O1. CIViC oncology exam\n",
         "Generated by `py -3 -m evaluation.o1_civic`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 23-10-2026, evening, "
         "before any download: O1». CIViC (CC0) predictive sensitivity / response evidence, levels A–B, single drug, pairs not "
         "already PrimeKG indications or confirmed Open Targets approvals; production model (full graph) against popularity; "
         "candidates = approved drugs not indicated for the cancer.\n",
         f"Cancers: {res['diseases']}; positive pairs: {res['positives']} (CIViC pairs already known as indications, left out: "
         f"{n_known}).\n", "| Set | OREVID Recall@100 | Popularity | Difference (95 % CI) |", "|---|---|---|---|",
         f"| all positives (deciding) | {res['orevid']:.3f} | {res['popularity']:.3f} | {d3(res['diff'])} |",
         f"| without an Open Targets clinical record for the pair ({res['new_positives']} positives) | {res['orevid_new']:.3f} | "
         f"{res['popularity_new']:.3f} | {d3(res['diff_new'])} |", "",
         f"**Decision:** {'claim supported' if res['claim'] else 'claim not supported'}.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "O1_CIVIC.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    main()
