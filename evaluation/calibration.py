"""Calibrated probability per candidate (docs/IMPROVEMENT_PLAN.md, I2; decision rule fixed there before running).

Unit: every pair in the top 25 of a test disease of the temporal validation (evaluation/temporal.py), shown or
hidden. Features fixed in the plan: website section, rank bucket (1-5, 6-10, 11-25), disease gene-set size bin
(< 100, 100-499, ≥ 500), hard flag (near-identical neighbour), ≥ 3 specific shared genes. Logistic regression
(no interactions) fitted on the C1 = 2012 set, evaluated on C2 = 2015 (outcome: phase 3 or approval after the
cutoff). Baseline: the section-only rates (fitted on C1 in the same way); the rates the website shows today
(external exam) are reported too. Decision: shown on the website only if, at C2, the Brier score is at least 5 %
(relative) better than the section-only baseline and the calibration slope is within 0.8-1.25.

    py -3 -m evaluation.calibration      # -> docs/CALIBRATION.md, data/eval/calibration.json
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
FEATURES = ["section", "rank", "size", "hard", "specific"]
WEBSITE_RATES = {"extension": 0.126, "shared genes": 0.043, "hidden": 0.015}  # external exam, docs/EVIDENCE_CI.md
B = 2000


def design(df, cols, levels=None):
    X = pd.get_dummies(df[cols].astype(str), drop_first=False)
    if levels is not None:
        X = X.reindex(columns=levels, fill_value=0)
    return X.astype(float)


def fit(df, cols):
    from sklearn.linear_model import LogisticRegression
    X = design(df, cols)
    m = LogisticRegression(C=1e6, max_iter=5000).fit(X.to_numpy(), df.y.to_numpy())
    return lambda d: m.predict_proba(design(d, cols, X.columns).to_numpy())[:, 1], m, list(X.columns)


def scores(y, p):
    from sklearn.linear_model import LogisticRegression
    p = np.clip(p, 1e-6, 1 - 1e-6)
    brier = float(np.mean((p - y) ** 2))
    logloss = float(-np.mean(y * np.log(p) + (1 - y) * np.log(1 - p)))
    lp = np.log(p / (1 - p)).reshape(-1, 1)
    r = LogisticRegression(C=1e6).fit(lp, y)
    return {"brier": brier, "log_loss": logloss, "slope": float(r.coef_[0][0]), "intercept": float(r.intercept_[0])}


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.temporal import pairs
    load = lambda C: dict(np.load(ROOT / "data" / "eval" / f"temporal_C{C}_extra_qtl.npz", allow_pickle=True))
    tr, te = pairs(load(2012)), pairs(load(2015))
    full, model, cols = fit(tr, FEATURES)
    sect, _, _ = fit(tr, ["section"])
    preds = {"model (all features)": full(te), "section only (C1 rates)": sect(te),
             "website rates (external exam)": te.section.map(WEBSITE_RATES).to_numpy()}
    y = te.y.to_numpy()
    res = {k: scores(y, p) for k, p in preds.items()}
    # disease-level bootstrap of the relative Brier improvement over the section-only baseline
    rng = np.random.default_rng(0)
    groups = te.groupby("disease").indices
    keys = list(groups)
    gain = []
    for _ in range(B):
        idx = np.concatenate([groups[k] for k in rng.choice(keys, len(keys))])
        b0 = np.mean((preds["section only (C1 rates)"][idx] - y[idx]) ** 2)
        b1 = np.mean((preds["model (all features)"][idx] - y[idx]) ** 2)
        gain.append(1 - b1 / b0)
    g = 1 - res["model (all features)"]["brier"] / res["section only (C1 rates)"]["brier"]
    lo, hi = np.percentile(gain, [2.5, 97.5])
    slope = res["model (all features)"]["slope"]
    adopted = bool(g >= 0.05 and 0.8 <= slope <= 1.25)
    # reliability: deciles of the predicted probability
    p = preds["model (all features)"]
    bins = pd.qcut(p, 10, duplicates="drop")
    rel = pd.DataFrame({"p": p, "y": y, "bin": bins}).groupby("bin", observed=True).agg(predicted=("p", "mean"),
                                                                                       observed=("y", "mean"), n=("y", "size"))
    coef = dict(zip(cols, model.coef_[0].round(3)))
    out = {"train_pairs": len(tr), "test_pairs": len(te), "train_rate": float(tr.y.mean()), "test_rate": float(y.mean()),
           "scores": res, "brier_gain": [g, lo, hi], "adopted": adopted, "coefficients": coef,
           "intercept": float(model.intercept_[0])}
    (ROOT / "data" / "eval" / "calibration.json").write_text(json.dumps(out, indent=1), "utf-8")
    L = ["# Calibrated probability per candidate (I2)\n",
         "Generated by `py -3 -m evaluation.calibration`. Protocol and decision rule: `docs/IMPROVEMENT_PLAN.md` (I2), fixed "
         "before running. Unit: every pair in the top 25 of a test disease of the temporal validation (`docs/TEMPORAL.md`); "
         "outcome: the pair reached phase 3 or approval after the cutoff. Fitted on the 2012 cutoff, evaluated on 2015.\n",
         f"Pairs: {len(tr):,} at 2012 ({100 * tr.y.mean():.2f} % positive), {len(te):,} at 2015 ({100 * y.mean():.2f} % positive).\n",
         "| Prediction | Brier | Log loss | Calibration slope | Calibration intercept |", "|---|---|---|---|---|"]
    for k, v in res.items():
        L.append(f"| {k} | {v['brier']:.5f} | {v['log_loss']:.4f} | {v['slope']:.2f} | {v['intercept']:.2f} |")
    L += ["", f"Relative Brier improvement of the model over the section-only rates: {100 * g:.1f} % "
              f"(95 % interval resampling diseases {100 * lo:.1f} to {100 * hi:.1f} %).\n",
          f"**Decision:** {'adopted' if adopted else 'not adopted'} (rule: improvement ≥ 5 % and slope within 0.8–1.25; "
          f"here {100 * g:.1f} % and {slope:.2f}). {'' if adopted else 'The website keeps the section rates.'}\n",
          "Reliability on 2015 (deciles of the predicted probability):\n", "| Predicted | Observed | Pairs |", "|---|---|---|"]
    L += [f"| {100 * r.predicted:.2f} % | {100 * r.observed:.2f} % | {int(r.n):,} |" for _, r in rel.iterrows()]
    L += ["", "Coefficients (log-odds, fitted on 2012):\n", "| Feature | Coefficient |", "|---|---|"]
    L += [f"| {k} | {v:+.3f} |" for k, v in coef.items()]
    (ROOT / "docs" / "CALIBRATION.md").write_text("\n".join(L) + "\n", "utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
