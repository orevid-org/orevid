"""T3: TxGNN on the dated temporal test (docs/IMPROVEMENT_PLAN.md, «Registered 24-10-2026: T3»).

    py -3 -m evaluation.t3_txgnn prepare 2015   # data/eval/split_temporal<C>_1.npy (2 = removed by T2) + diseases CSV
    (WSL) python evaluation/txgnn_wsl.py --label .../split_temporal2015_1.npy --test-size 0.0515 --tag temporal2015 \
          --diseases .../temporal_2015_diseases.csv ...
    py -3 -m evaluation.t3_txgnn report         # -> docs/T3_TXGNN_TEMPORAL.md
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
EVAL = ROOT / "data" / "eval"
TEST_SIZE = {2012: 0.0512, 2015: 0.0515}  # only to give TxGNN's cache folders distinct names


def prepare(C):
    from evaluation.temporal import clinical, cutoff_mask, drug_years
    from evaluation.txgnn import PRODUCTION, load_kg
    kg = load_kg()
    clin, _ = clinical()
    keep, leak, removed = cutoff_mask(kg, clin, C, drug_years())
    label = np.where(keep, 0, 2).astype(np.int8)
    np.save(EVAL / f"split_temporal{C}_1.npy", label)
    z = np.load(EVAL / f"temporal_C{C}_{PRODUCTION}_dated.npz", allow_pickle=True)
    nodes = pd.read_csv(ROOT / "data" / "raw" / "txgnn" / "node.csv", sep="\t", dtype=str)
    m = pd.DataFrame({"node_index": z["D"].astype(int)})
    m["node_id"] = nodes.node_id.to_numpy()[m.node_index]
    m.to_csv(EVAL / f"temporal_{C}_diseases.csv", index=False)
    print(f"C={C}: {int((label == 2).sum()):,} edges marked test (T2 removes {removed:,}); {len(m)} diseases to score")


def scores(C, drugs, D):
    from evaluation.external_exam import N_PKG
    from evaluation.txgnn import _id
    f = EVAL / "txgnn_predictions" / f"TxGNN_temporal{C}_external.parquet"
    d = pd.read_parquet(f)
    d = d[d.relation == "indication"]
    nodes = pd.read_csv(ROOT / "data" / "raw" / "txgnn" / "node.csv", sep="\t", dtype=str)
    idx = {(t, _id(i)): int(n) for n, i, t in zip(nodes.node_index, nodes.node_id, nodes.node_type)}
    mi = np.array([idx.get(("disease", _id(i)), -1) for i in d.disease_id])
    fi = np.array([idx.get(("drug", _id(i)), -1) for i in d.drug_id])
    pos_m = {int(m): j for j, m in enumerate(D)}
    pos_f = np.full(N_PKG, -1)
    pos_f[drugs] = np.arange(len(drugs))
    res = np.full((len(drugs), len(D)), np.nan, np.float32)
    ok = np.isin(mi, list(pos_m)) & (fi >= 0)
    res[pos_f[fi[ok]], [pos_m[m] for m in mi[ok]]] = d.score.to_numpy()[ok]
    lo = np.nanmin(res) if np.isfinite(res).any() else 0
    return np.nan_to_num(res, nan=lo - 1), int(np.isnan(res).all(axis=0).sum())


def report():
    sys.stdout.reconfigure(encoding="utf-8")
    from evaluation.temporal import boot_mean, recall_per_disease
    from evaluation.txgnn import PRODUCTION
    out = {}
    for C in (2012, 2015):
        f = EVAL / f"temporal_C{C}_{PRODUCTION}_dated.npz"
        if not f.exists() or not (EVAL / "txgnn_predictions" / f"TxGNN_temporal{C}_external.parquet").exists():
            continue
        z = dict(np.load(f, allow_pickle=True))
        zo = EVAL / f"temporal_C{C}_extra_no_ot_dated.npz"
        zo = dict(np.load(zo, allow_pickle=True)) if zo.exists() else None
        S_tx, missing = scores(C, z["drugs"], z["D"])
        deg = np.repeat(z["degree"][:, None], len(z["D"]), axis=1).astype(np.float32)
        rng = np.random.default_rng(0)
        res = {"diseases": len(z["D"]), "txgnn_missing": missing, "recall": {}, "paired": {}}
        for key in [k[4:] for k in z if k.startswith("pos|")]:
            pos = list(z[f"pos|{key}"])
            r = {"OREVID": recall_per_disease(z["S_rank"], z["cand"], pos), "TxGNN": recall_per_disease(S_tx, z["cand"], pos),
                 "Popularity": recall_per_disease(deg, z["cand"], pos)}
            if zo is not None and np.array_equal(zo["D"], z["D"]):
                r["OREVID without Open Targets"] = recall_per_disease(zo["S_rank"], zo["cand"], list(zo[f"pos|{key}"]))
            res["recall"][key] = {m: boot_mean(v, rng) for m, v in r.items()} | {"positives": int(sum(map(len, pos)))}
            res["paired"][key] = {"OREVID − TxGNN": boot_mean(r["OREVID"] - r["TxGNN"], rng),
                                  "TxGNN − popularity": boot_mean(r["TxGNN"] - r["Popularity"], rng)}
            if "OREVID without Open Targets" in r:
                res["paired"][key]["OREVID without Open Targets − TxGNN"] = boot_mean(r["OREVID without Open Targets"] - r["TxGNN"], rng)
        out[C] = res
    (EVAL / "t3_txgnn.json").write_text(json.dumps(out, indent=1, default=float), "utf-8")
    f3 = lambda x: f"{x[0]:.3f} ({x[1]:.3f}–{x[2]:.3f})"
    L = ["# T3. TxGNN on the dated temporal test\n",
         "Generated by `py -3 -m evaluation.t3_txgnn report`. Protocol: `docs/IMPROVEMENT_PLAN.md`, «Registered 24-10-2026: T3». "
         "TxGNN (official code, benchmark hyperparameters) trained on exactly T2's cutoff graph (P83) and evaluated on T2's "
         "test diseases, candidates and positives; OREVID = production model on T2; Recall@100 means over diseases with 95 % "
         "intervals resampling diseases.\n"]
    for C, r in out.items():
        L += [f"## Cutoff {C}{' (confirmation)' if C == 2015 else ' (development)'}\n",
              f"{r['diseases']} test diseases; TxGNN has no score for {r['txgnn_missing']}.\n",
              "| Positives | n | OREVID | TxGNN | Popularity | OREVID − TxGNN | TxGNN − popularity |", "|---|---|---|---|---|---|---|"]
        for k, v in r["recall"].items():
            L.append(f"| {k} | {v['positives']:,} | {f3(v['OREVID'])} | {f3(v['TxGNN'])} | {f3(v['Popularity'])} | "
                     f"{f3(r['paired'][k]['OREVID − TxGNN'])} | {f3(r['paired'][k]['TxGNN − popularity'])} |")
        if any("OREVID without Open Targets − TxGNN" in v for v in r["paired"].values()):
            L += ["", "Same data as TxGNN (OREVID without any Open Targets feature):\n",
                  "| Positives | OREVID without Open Targets | OREVID without Open Targets − TxGNN |", "|---|---|---|"]
            for k, v in r["recall"].items():
                if "OREVID without Open Targets" in v:
                    L.append(f"| {k} | {f3(v['OREVID without Open Targets'])} | {f3(r['paired'][k]['OREVID without Open Targets − TxGNN'])} |")
        L.append("")
    if 2015 in out:
        lo, hi = out[2015]["paired"]["primary"]["OREVID − TxGNN"][1:3]
        verdict = "above" if lo > 0 else ("below" if hi < 0 else "not distinguishable from")
        L += [f"**Decision at C2 (primary):** OREVID − TxGNN {lo:.3f} to {hi:.3f}: OREVID ranks later phase 3 / approved uses "
              f"**{verdict}** TxGNN.\n"]
    text = "\n".join(L) + "\n"
    (ROOT / "docs" / "T3_TXGNN_TEMPORAL.md").write_text(text, "utf-8")
    print(text)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    prepare(int(sys.argv[2])) if sys.argv[1] == "prepare" else report()
