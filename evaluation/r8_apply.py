"""R8c (P91), adopted by the author: rebuild the pages where the rule hides a candidate, and check that nothing else
changes. The rebuilt pages go to the website with `py -3 -m web.build --patch-rebuilt data/eval/r8_pages.pkl`.

    py -3 -m evaluation.r8_apply     # -> data/eval/r8_pages.pkl, docs/R8C_APPLIED.md
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from web.build import DEST, DiseasePages, valid_similar
    P = DiseasePages()
    g = P.g
    cancer_names = {g.name(f) for f in P.cancer_drugs}
    pages = {}
    for fj in sorted((DEST / "d").glob("*.json")):
        pages.update({int(k): v for k, v in json.loads(fj.read_text("utf-8")).items()})
    affected = []
    for d, v in pages.items():
        if set(P.twins.get(d, {d})) & P.neoplastic:
            continue
        for c in v.get("candidates") or []:
            if c["name"] not in cancer_names or "neighbour" in c.get("lines", []):
                continue
            via = [m[0] for e in c.get("expl", []) if e["t"] == "similar" for m in e["m"] if valid_similar(m)]
            if via and all(m in P.neoplastic_names for m in via):
                affected.append(d)
                break
    rows, rebuilt = [], {}
    for k, d in enumerate(affected):
        new = P.disease(d)
        rebuilt[d] = new
        old = pages[d]
        for sec in ("extensions", "candidates", "no_use"):
            a = {c["name"] for c in old.get(sec) or []}
            b = {c["name"] for c in new.get(sec) or []}
            rows += [(old["name"], sec, "removed", n) for n in sorted(a - b)]
            rows += [(old["name"], sec, "added", n) for n in sorted(b - a)]
        if (k + 1) % 100 == 0:
            print(f"  {k + 1}/{len(affected)}", flush=True)
    pd.to_pickle((affected, rows, rebuilt), ROOT / "data" / "eval" / "r8_pages.pkl")
    ch = pd.DataFrame(rows, columns=["disease", "section", "change", "drug"])
    removed = ch[ch.change == "removed"]
    odd = ch[(ch.change == "added") | ~ch.drug.isin(cancer_names) | (ch.section != "candidates")]
    L = ["# R8c applied (P91)\n", "Generated by `py -3 -m evaluation.r8_apply`.\n",
         f"Pages rebuilt: {len(affected)}; candidates hidden: {len(removed)}; other changes (should be none): {len(odd)}.\n",
         "| Disease | Section | Change | Drug |", "|---|---|---|---|"]
    L += [f"| {r.disease} | {r.section} | {r.change} | {r.drug} |" for r in ch.sort_values(["disease", "drug"]).itertuples()]
    (ROOT / "docs" / "R8C_APPLIED.md").write_text("\n".join(L) + "\n", "utf-8")
    print("\n".join(L[:3]))
    if len(odd):
        print(odd.head(20).to_string())


if __name__ == "__main__":
    main()
